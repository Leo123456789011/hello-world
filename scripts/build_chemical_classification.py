def tagged_rows():
    out = []
    for name, cat, bu, cluster, reason in ROWS:
        key = (bu, cluster)
        if key not in MANAGER:
            raise SystemExit(f"未知产业群: {name} {bu}/{cluster}")
        out.append((name, cat, bu, cluster, MANAGER[key], reason))
    return out


def style_header(ws, n_cols):
    fill = PatternFill("solid", fgColor="1F4E79")
    font = Font(name="微软雅黑", bold=True, color="FFFFFF", size=11)
    align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    thin = Border(
        left=Side(style="thin", color="BDD7EE"),
        right=Side(style="thin", color="BDD7EE"),
        top=Side(style="thin", color="BDD7EE"),
        bottom=Side(style="thin", color="BDD7EE"),
    )
    for col in range(1, n_cols + 1):
        cell = ws.cell(1, col)
        cell.fill = fill
        cell.font = font
        cell.alignment = align
        cell.border = thin
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    ws.row_dimensions[1].height = 22


def style_body(ws, n_rows, n_cols, manager_col=None):
    font = Font(name="微软雅黑", size=10)
    align = Alignment(horizontal="left", vertical="center", wrap_text=True)
    center = Alignment(horizontal="center", vertical="center")
    thin = Border(
        left=Side(style="thin", color="D9E2F3"),
        right=Side(style="thin", color="D9E2F3"),
        top=Side(style="thin", color="D9E2F3"),
        bottom=Side(style="thin", color="D9E2F3"),
    )
    stripe = PatternFill("solid", fgColor="F2F2F2")
    manager_fills = {
        "韩永": PatternFill("solid", fgColor="FFF2CC"),
        "孙伟卓": PatternFill("solid", fgColor="E2EFDA"),
        "王媛媛": PatternFill("solid", fgColor="FCE4D6"),
        "李春燕": PatternFill("solid", fgColor="DDEBF7"),
        "王能": PatternFill("solid", fgColor="E2D5F1"),
        "初晓": PatternFill("solid", fgColor="F8CBAD"),
        "张超": PatternFill("solid", fgColor="C6EFCE"),
        "毛临江": PatternFill("solid", fgColor="DDEBF7"),
        "王舒同": PatternFill("solid", fgColor="DDEBF7"),
        "牛磊": PatternFill("solid", fgColor="DDEBF7"),
    }
    for r in range(2, n_rows + 2):
        for c in range(1, n_cols + 1):
            cell = ws.cell(r, c)
            cell.font = font
            cell.alignment = center if c in (3, 4, 5) else align
            cell.border = thin
            if r % 2 == 0:
                cell.fill = stripe
        if manager_col:
            mgr = ws.cell(r, manager_col).value
            fill = manager_fills.get(mgr)
            if fill:
                ws.cell(r, manager_col).fill = fill


def autosize(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def add_sheet(wb, title, headers, rows, widths, manager_col=None):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for row in rows:
        ws.append(list(row))
    style_header(ws, len(headers))
    style_body(ws, len(rows), len(headers), manager_col=manager_col)
    autosize(ws, widths)
    ws.sheet_properties.tabColor = "1F4E79"
    return ws


