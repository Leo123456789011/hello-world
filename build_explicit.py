def classify(name: str):
    if name in ("个人", "个体", "个体期货") or name in PERSON_NAMES:
        return ("个人客户", "个人客户", "个人客户")
    if name in OTHER_MARKERS:
        return ("其他", "其他", "")
    if name in MANUAL:
        return MANUAL[name]
    raise ValueError(f"Unclassified: {name}")


